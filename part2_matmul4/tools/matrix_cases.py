#!/usr/bin/env python3
"""Generate matrix expectations using Part I's exact-rational oracle API.
This does not execute Part I's directed or exhaustive unit regressions.
"""
from pathlib import Path
import sys
import json
import random
from fractions import Fraction

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'part1_fp8/tools'))
from generate_vectors import evaluate, quantize, classify, value


def product(a, b):
    c = [[0]*4 for _ in range(4)]
    flags = 0
    for i in range(4):
        for j in range(4):
            acc = 0
            for k in range(4):
                mul, mf = evaluate('mul', a[i][k], b[k][j])
                acc, af = evaluate('add', acc, mul)
                flags |= mf | af
            c[i][j] = acc
    return c, flags


def columns(m):
    return [sum(m[i][k] << (8*i) for i in range(4)) for k in range(4)]


def rows(m):
    return [sum(m[k][j] << (8*j) for j in range(4)) for k in range(4)]


def describe(code):
    kind = classify(code)
    return ('-' if code & 128 else '+')+'Inf' if kind == 'inf' else str(value(code))


def main():
    out = ROOT/'part2_matmul4'
    rng = random.Random(32026)
    pool = [quantize(Fraction(x, 2))[0] for x in [-3, -2, -1, 1, 2, 3]]
    while True:
        a = [[rng.choice(pool) for _ in range(4)] for _ in range(4)]
        b = [[rng.choice(pool) for _ in range(4)] for _ in range(4)]
        c, flags = product(a,b)
        if flags == 0:
            break
    ae = [r[:] for r in a]
    be = [r[:] for r in b]
    ae[3][3] = 0x60  # 8.0
    be[3][3] = 0x40  # 2.0: finite multiplication overflow in PE33.
    ce, ef = product(ae,be)
    assert ef == 17, (ef, ce)
    cases = [(a,b,c,flags),(ae,be,ce,ef)]
    lines = ['// Generated by tools/matrix_cases.py; all C entries independently computed.',
             'task automatic load_case(input integer which);', 'begin', 'case (which)']
    doc = ['# Matrix test cases', '', 'Seed: 32026. Each multiply and add is rounded separately using the unchanged Part I exact-rational model.', '']
    records=[]
    for n,(aa,bb,cc,ff) in enumerate(cases,1):
        lines.append(f'{n}: begin')
        for k in range(4):
            lines += [f"a_words[{k}] = 32'h{columns(aa)[k]:08x};",f"b_words[{k}] = 32'h{rows(bb)[k]:08x};",f"expected_words[{k}] = 32'h{columns(cc)[k]:08x};"]
        lines += [f"expected_flags = 5'b{ff:05b};", 'end']
        doc += [f'## Case {n}: '+('clean' if n==1 else 'finite overflow'), '', f'Expected combined flags: `{ff:05b}`.', '']
        for name,mat in [('A',aa),('B',bb),('C',cc)]:
            doc += [f'### {name}: decimal (hex)', '', '| row | col 0 | col 1 | col 2 | col 3 |','|---|---|---|---|---|']
            doc += ['| '+str(i)+' | '+' | '.join(f'{describe(x)} (`{x:02x}`)' for x in row)+' |' for i,row in enumerate(mat)]
            doc += ['']
        records.append(dict(case=n,A=aa,B=bb,C=cc,flags=ff))
    lines += ['default: $fatal(1, "Unknown testcase");','endcase','end','endtask']
    (out/'tb/cases.svh').write_text('\n'.join(lines)+'\n')
    (out/'docs/MATRICES.md').write_text('\n'.join(doc)+'\n')
    (out/'docs/matrices.json').write_text(json.dumps(records,indent=2)+'\n')
    print('Generated two FP8 matrix datasets; expected flags 00000 and 10001.')


if __name__ == '__main__':
    main()
