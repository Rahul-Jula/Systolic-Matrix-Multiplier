#!/usr/bin/env python3
"""Deterministic 8x8 expectations from Part I's independent rational oracle."""
from pathlib import Path
from fractions import Fraction
import json
import random
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'part1_fp8/tools'))
from generate_vectors import evaluate, quantize, classify, value


def product(a, b):
    c = [[0] * 8 for _ in range(8)]
    flags = 0
    for i in range(8):
        for j in range(8):
            acc = 0
            for k in range(8):
                p, mf = evaluate('mul', a[i][k], b[k][j])
                acc, af = evaluate('add', acc, p)
                flags |= mf | af
            c[i][j] = acc
    return c, flags


def pack_column(m, k):
    return sum(m[i][k] << (8*i) for i in range(8))


def pack_row(m, k):
    return sum(m[k][j] << (8*j) for j in range(8))


def describe(code):
    kind = classify(code)
    if kind == 'inf':
        return '-Inf' if code & 128 else '+Inf'
    if kind == 'nan':
        return 'NaN'
    return str(value(code))


def main():
    out = ROOT / 'part3_matmul8'
    (out / 'tb').mkdir(parents=True, exist_ok=True)
    (out / 'docs').mkdir(parents=True, exist_ok=True)
    rng = random.Random(320268)
    ones = [[0x30]*8 for _ in range(8)]
    pool = [quantize(Fraction(v, 2))[0] for v in [-2, -1, 0, 1, 2]]
    varied_a = [[rng.choice(pool) for _ in range(8)] for _ in range(8)]
    varied_b = [[rng.choice(pool) for _ in range(8)] for _ in range(8)]
    # One controlled finite overflow in bottom-right PE, with zero padding.
    exceptional_a = [[0]*8 for _ in range(8)]
    exceptional_b = [[0]*8 for _ in range(8)]
    exceptional_a[7][7] = 0x60
    exceptional_b[7][7] = 0x40
    cases = [('all ones', ones, ones), ('varied signed', varied_a, varied_b),
             ('finite overflow', exceptional_a, exceptional_b)]
    lines = ['// Generated by tools/matrix_cases.py. C is independently computed.',
             'task automatic load_case(input integer which);', 'begin', 'case (which)']
    doc = ['# Part III matrix cases', '', 'Seed: 320268. Multiply and add round separately using the Part I exact-rational model.', '']
    records = []
    for n, (name, a, b) in enumerate(cases, 1):
        c, flags = product(a, b)
        assert flags == (17 if n == 3 else 0)
        lines += [f'{n}: begin']
        for k in range(8):
            lines += [f"a_words[{k}] = 64'h{pack_column(a,k):016x};",
                      f"b_words[{k}] = 64'h{pack_row(b,k):016x};",
                      f"expected_words[{k}] = 64'h{pack_column(c,k):016x};"]
        lines += [f"expected_flags = 5'b{flags:05b};", 'end']
        doc += [f'## Case {n}: {name}', '', f'Expected flags: `{flags:05b}`.', '']
        for title, matrix in [('A', a), ('B', b), ('C', c)]:
            doc += [f'### {title}: decimal (hex)', '', '| row | ' + ' | '.join(str(j) for j in range(8)) + ' |',
                    '|---|' + '---|'*8]
            doc += ['| '+str(i)+' | '+' | '.join(f'{describe(x)} (`{x:02x}`)' for x in row)+' |'
                    for i, row in enumerate(matrix)]
            doc += ['']
        records.append(dict(case=n, name=name, A=a, B=b, C=c, flags=flags))
    lines += ['default: $fatal(1,"Unknown testcase");', 'endcase', 'end', 'endtask']
    for filename, content in [('tb/cases.svh', '\n'.join(lines)+'\n'),
                              ('docs/MATRICES.md', '\n'.join(doc)+'\n'),
                              ('docs/matrices.json', json.dumps(records, indent=2)+'\n')]:
        with (out/filename).open('w', encoding='utf-8', newline='\n') as stream:
            stream.write(content)
    print('Generated 3 datasets: 64 results each; flags 00000, 00000, 10001.')


if __name__ == '__main__':
    main()
